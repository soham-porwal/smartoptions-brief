"""Lane CH: write app/chat/universe.js (S&P 500 symbol/name/sector list) for the chat router.
Source: data/cache/brief/constituents.json written by lane BD. Run: py -3.12 app/chat/build_universe.py"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = json.loads((root / 'data/cache/brief/constituents.json').read_text(encoding='utf-8'))
syms, names, secs = src['symbols'], src['names'], src['sectors']
get = lambda m, s, i: m.get(s) if isinstance(m, dict) else m[i]
rows = [[s, get(names, s, i) or '', get(secs, s, i) or ''] for i, s in enumerate(syms)]
meta = {'source': src.get('source'), 'url': src.get('url'), 'retrieved_at': src.get('retrieved_at'), 'count': len(rows)}
out = ('/* Generated by app/chat/build_universe.py from lane BD constituents cache. Do not edit. */\n'
       "(function (r) { const U = {meta: %s, rows: %s};\n"
       "  if (typeof module !== 'undefined' && module.exports) module.exports = U; r.SmartOptionsUniverse = U; })"
       "(typeof window !== 'undefined' ? window : globalThis);\n") % (json.dumps(meta), json.dumps(rows, separators=(',', ':')))
(root / 'app/chat/universe.js').write_text(out, encoding='utf-8')
print(len(rows), meta)
